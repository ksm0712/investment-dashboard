import type { ResearchRun } from "./ai-research-types.ts";

function statusMark(status: string) {
  if (status === "supported") return "SUPPORTED";
  if (status === "contradicted") return "CONTRADICTED";
  return "UNCLEAR";
}

export function researchRunToMarkdown(run: ResearchRun, companyName?: string) {
  const lines = [
    `# ${companyName ? `${companyName} — ` : ""}Thesis evidence review`,
    "",
    `**Reviewed:** ${run.createdAt.slice(0, 10)}  `,
    `**Evidence verdict:** ${run.analysis.evidenceSignal}  `,
    `**Numerical action (separate engine):** ${run.numericalAction}`,
    "",
    "## Thesis",
    "",
    run.thesis,
    "",
    "## Summary",
    "",
    run.analysis.summary,
    "",
    "## Claim checks",
    "",
    ...run.analysis.thesisChecks.flatMap((check) => [
      `### ${statusMark(check.status)} — ${check.statement}`,
      "",
      `${check.explanation}${check.citationIds.length ? ` (${check.citationIds.join(", ")})` : ""}`,
      "",
    ]),
  ];
  if (run.analysis.evidenceGaps.length) {
    lines.push("## Evidence still needed", "", ...run.analysis.evidenceGaps.map((gap) => `- **${gap.claim}:** ${gap.neededEvidence}`), "");
  }
  if (run.analysis.monitoringQuestions.length) {
    lines.push("## Monitoring questions", "", ...run.analysis.monitoringQuestions.map((question) => `- ${question}`), "");
  }
  lines.push("## Source passages", "", ...run.citations.flatMap((citation) => [
    `### ${citation.chunkId} — ${citation.sourceTitle}`,
    "",
    `> ${citation.excerpt.replace(/\n+/g, " ")}`,
    "",
    citation.sourceUrl ? `[Open source](${citation.sourceUrl})` : "Source URL unavailable",
    "",
  ]));
  lines.push("---", `Generated by Thesis evidence pipeline v${run.pipelineVersion || "legacy"}. Verify source passages before making a decision.`);
  return `${lines.join("\n").trim()}\n`;
}

export function monitoringChecklistText(run: ResearchRun) {
  const items = [
    ...run.analysis.evidenceGaps.map((gap) => `${gap.claim}: ${gap.neededEvidence}`),
    ...run.analysis.monitoringQuestions,
  ];
  return items.map((item, index) => `${index + 1}. ${item}`).join("\n");
}
